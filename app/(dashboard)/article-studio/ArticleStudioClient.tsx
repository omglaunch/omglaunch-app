  async function handleGenerateArticle() {
    if (!selectedBriefId) {
      toast.error('Select a content brief first.');
      return;
    }

    if (!projectId.trim()) {
      toast.error('Select a project before generating an article.');
      return;
    }

    if (generationInFlightRef.current || isGenerating) {
      return;
    }

    generationInFlightRef.current = true;
    setIsGenerating(true);

    try {
      const response = await fetch('/api/generate-article', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ briefId: selectedBriefId }),
      });

      const payload = await response.json().catch(() => ({}));

      if (!response.ok) {
        const rawMessage =
          typeof payload === 'object' && payload !== null && 'error' in payload
            ? String(payload.error)
            : 'Article generation failed. Please try again.';

        let message = rawMessage;
        if (rawMessage.includes('503') || rawMessage.includes('high demand')) {
          message =
            'The AI model is temporarily overloaded. Please wait a moment and click Regenerate Article.';
        }

        throw new Error(message);
      }

      const parsed = parseGeneratedArticleResponse(
        payload,
        selectedBrief?.targetKeyword || ''
      );

      if (!parsed) {
        throw new Error('Article generation returned invalid data.');
      }

      const { article, seoTitle: generatedSeoTitle, metaDescription: generatedMetaDescription } =
        parsed;

      const optimizedMetaDescription = await ensureGeoOptimizedMetaDescription({
        targetKeyword: selectedBrief?.targetKeyword || '',
        seoTitle: generatedSeoTitle,
        articleContent: article.content,
        briefId: selectedBriefId,
        currentMeta: generatedMetaDescription,
      });

      setActiveArticle(article);
      setEditorTitle(article.title);
      applyGeneratedFieldsToEditor(
        {
          content: article.content,
          seoTitle: generatedSeoTitle,
          metaDescription: optimizedMetaDescription,
        },
        {
          setDraftContent,
          setSeoTitle,
          setMetaDescription,
          setLastSavedSnapshot: snapshot => {
            lastSavedSnapshotRef.current = snapshot;
          },
        }
      );
      syncBriefArticleState(selectedBriefId, article);
      setSaveStatus('unsaved');

      let draftIdForSave = historyId;
      if (!draftIdForSave && selectedBrief) {
        draftIdForSave = await loadHistoryIdForBrief(selectedBrief);
      }

      void saveDraft({
        silent: true,
        contentOverride: article.content,
        seoTitleOverride: generatedSeoTitle,
        metaDescriptionOverride: optimizedMetaDescription,
        draftIdOverride: draftIdForSave,
        articleIdOverride: article.id,
      });
      toast.success('Article generated successfully.');
    } catch (generateError) {
      toast.error(
        generateError instanceof Error
          ? generateError.message
          : 'Article generation failed. Please try again.'
      );
    } finally {
      generationInFlightRef.current = false;
      setIsGenerating(false);
      setAwaitingAutoGenerate(false);
    }
  }

  useEffect(() => {
    if (!isEditorActive) {
      return;
    }

    const currentSnapshot = createDraftSnapshot(draftContent, seoTitle, metaDescription);
    if (draftSnapshotsEqual(currentSnapshot, lastSavedSnapshotRef.current)) {
      return;
    }

    setSaveStatus(current => (current === 'saving' ? current : 'unsaved'));
  }, [draftContent, seoTitle, metaDescription, isEditorActive]);

