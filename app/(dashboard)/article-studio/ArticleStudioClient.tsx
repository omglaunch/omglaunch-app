  async function handleExportArticle(format: ArticleExportFormat) {
    if (!draftContent.trim()) {
      toast.error('No article content available to export.');
      return;
    }

    const exportName = getExportNameSource(editorTitle, activeArticle, selectedBrief);
    const filename = buildExportFilename(exportName, format);

    setIsExporting(true);

    try {
      if (format === 'md') {
        const blob = new Blob([draftContent], { type: 'text/markdown;charset=utf-8' });
        triggerFileDownload(blob, filename);
        toast.success('Markdown file downloaded.');
        return;
      }

      if (format === 'txt') {
        const plainText = markdownToPlainText(draftContent);
        const blob = new Blob([plainText], { type: 'text/plain;charset=utf-8' });
        triggerFileDownload(blob, filename);
        toast.success('Text file downloaded.');
        return;
      }

      const response = await fetch('/api/export-docx', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          markdown: draftContent,
          title: exportName,
        }),
      });

      if (!response.ok) {
        const payload = await response.json().catch(() => ({}));
        const message =
          typeof payload === 'object' && payload !== null && 'error' in payload
            ? String(payload.error)
            : 'DOCX export failed. Please try again.';
        throw new Error(message);
      }

      const docxBlob = await response.blob();
      triggerFileDownload(docxBlob, filename);
      toast.success('Word document downloaded.');
    } catch (exportError) {
      toast.error(
        exportError instanceof Error ? exportError.message : 'Export failed. Please try again.'
      );
    } finally {
      setIsExporting(false);
    }
  }

