async function ensureGeoOptimizedMetaDescription(input: {
  targetKeyword: string;
  seoTitle: string;
  articleContent: string;
  briefId?: number;
  currentMeta?: string;
}): Promise<string> {
  const targetKeyword = input.targetKeyword.trim();
  const seoTitle = input.seoTitle.trim();
  const currentMeta = input.currentMeta?.trim() ?? '';

  if (
    currentMeta &&
    isMetaDescriptionAcceptable(currentMeta, targetKeyword)
  ) {
    return currentMeta;
  }

  try {
    const optimized = await fetchOptimizedMetaDescription({
      targetKeyword,
      seoTitle,
      articleContent: input.articleContent,
      briefId: input.briefId,
      existingMeta: currentMeta || undefined,
    });

    return optimized ?? currentMeta;
  } catch {
    return currentMeta;
  }
}

