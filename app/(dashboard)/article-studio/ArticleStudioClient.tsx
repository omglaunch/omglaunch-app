function SaveStatusIndicator({
  status,
}: {
  status: SaveStatus;
}) {
  if (status === 'idle') {
    return null;
  }

  const label =
    status === 'unsaved'
      ? 'Unsaved changes'
      : status === 'saving'
        ? 'Saving…'
        : status === 'saved'
          ? 'Saved to history'
          : 'Save failed';

  const className =
    status === 'unsaved'
      ? 'text-amber-600'
      : status === 'saving'
        ? 'text-muted-foreground'
        : status === 'saved'
          ? 'text-emerald-600'
          : 'text-red-600';

  return (
    <span className={cn('flex items-center gap-1.5 text-xs font-medium', className)}>
      {status === 'saving' ? <Loader2 className="h-3 w-3 animate-spin" /> : null}
      {label}
    </span>
  );
}

