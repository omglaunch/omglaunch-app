function resolveStudioModeFromParams(
  params: Pick<URLSearchParams, 'get'>
): ArticleStudioMode {
  const sourceRoute = params.get('sourceRoute')?.trim();
  const promptId = params.get('prompt_id')?.trim() ?? params.get('gapId')?.trim();
  const autoGenerate = params.get('autoGenerate')?.trim();
  const clusters = params.get('clusters')?.trim();

  if (sourceRoute === 'ai-visibility' || promptId || autoGenerate === '1' || clusters) {
    return 'gap-analysis';
  }

  return 'classic';
}

